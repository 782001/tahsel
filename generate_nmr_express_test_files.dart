void _createExcelFile(String filePath, List<String> headers, List<List<dynamic>> rows) {
  var excel = Excel.createExcel();
  Sheet sheetObject = excel['Sheet1'];
  excel.setDefaultSheet('Sheet1');

  // Title rows at top (like real NMR Express report!)
  sheetObject.appendRow([TextCellValue('NMR Express')]);
  sheetObject.appendRow([TextCellValue('تاج')]);

  // Real Table Header Row
  sheetObject.appendRow(headers.map((e) => TextCellValue(e)).toList());
  for (var row in rows) {
    sheetObject.appendRow(row.map((e) => TextCellValue(e.toString())).toList());
  }

  var fileBytes = excel.save();
  if (fileBytes != null) {
    File(filePath)
      ..createSync(recursive: true)
      ..writeAsBytesSync(fileBytes);
    print('Generated Excel: $filePath');
  }
}

void _createCsvFile(String filePath, List<String> headers, List<List<dynamic>> rows) {
  final buffer = StringBuffer();
  buffer.writeln('"NMR Express"');
  buffer.writeln('"تاج"');
  buffer.writeln(headers.map((e) => '"$e"').join(','));
  for (var row in rows) {
    buffer.writeln(row.map((e) => '"${e.toString()}"').join(','));
  }
  File(filePath)
    ..createSync(recursive: true)
    ..writeAsStringSync(buffer.toString());
  print('Generated CSV: $filePath');
}
